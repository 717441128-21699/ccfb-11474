# 反向索引:归一化标题 -> 标准代码
_LOOKUP: dict[str, str] = {}
for _code, _titles in HEADING_SYNONYMS.items():
    for _t in _titles:
        _LOOKUP[_t] = _code
    _LOOKUP[_code] = _code


def normalize_heading(raw: str) -> str:
    """剥掉编号/括号/空白,返回标准章节代码;无法识别返回 ''。"""
    s = raw.strip()
    # 去常见包裹符号
    s = s.strip("　 ").strip("【】[]〔〕()（）<>《》")
    # 去开头编号:一、 1. 1、 (一) 第1章 等
    import re
    s = re.sub(
        r"^(第?[0-9０-９]+[章节条、.．)\s]*|[一二三四五六七八九十]+[、.．)\s]*"
        r"|[（(][一二三四五六七八九十0-9]+[)）]\s*)",
        "",
        s,
    ).strip(" 　:：.．、")
    if not s:
        return ""
    if s in _LOOKUP:
        return _LOOKUP[s]
    # 标题里包含同义词(如"药物相互作用及注意事项")
    for title, code in _LOOKUP.items():
        if len(title) >= 3 and title in s:
            return code
    return ""
